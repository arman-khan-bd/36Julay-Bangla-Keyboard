//! Cross-Distro Linux Driver for Bijoy Bangla Keyboard.
//! Supports Ubuntu, Debian, Fedora, Arch Linux, openSUSE, and all Linux distros.
//! Provides:
//! 1. Native IBus Engine generator and protocol runner (works on both Wayland & X11)
//! 2. Linux uinput/evdev virtual device driver
//! 3. X11 hook / XTest compatibility layer

use bijoy_core::{BijoyEngine, BijoyMode, EngineOutput};
use std::fs;
use std::io::{self, BufRead, Write};
use std::path::PathBuf;

pub fn is_linux_supported() -> bool {
    cfg!(target_os = "linux")
}

/// Generate official IBus component XML specification for Bijoy Bangla.
/// Can be installed to /usr/share/ibus/component/bijoy.xml
/// or ~/.local/share/ibus/component/bijoy.xml
