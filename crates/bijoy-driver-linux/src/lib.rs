/// Install IBus component XML into user's local directory or system directory
pub fn install_ibus_component(system_wide: bool, binary_path: &str) -> io::Result<PathBuf> {
    let target_dir = if system_wide {
        PathBuf::from("/usr/share/ibus/component")
    } else {
        let home = std::env::var("HOME").unwrap_or_else(|_| "/tmp".to_string());
        PathBuf::from(home).join(".local/share/ibus/component")
    };

    fs::create_dir_all(&target_dir)?;
    let file_path = target_dir.join("bijoy.xml");
    let xml = generate_ibus_xml(binary_path);
    fs::write(&file_path, xml)?;
    println!("[Bijoy Linux] IBus component installed at: {}", file_path.display());
    Ok(file_path)
}

/// Standalone Linux IBus engine runner that reads standard input key events
/// and outputs IBus commit/preedit commands.
pub struct LinuxIbusRunner {
    engine: BijoyEngine,
}

impl LinuxIbusRunner {
    pub fn new() -> Self {
        Self {
            engine: BijoyEngine::new(),
        }
    }

    pub fn set_mode(&mut self, mode: BijoyMode) {
        self.engine.set_mode(mode);
    }

    /// Process a key input character from IBus
    pub fn handle_key(&mut self, ch: char) -> EngineOutput {
        self.engine.process_char(ch)
    }

    /// Run interactive IBus IPC protocol loop
    pub fn run_loop(&mut self) -> io::Result<()> {
        let stdin = io::stdin();
        let mut stdout = io::stdout();
        let reader = stdin.lock();

        for line in reader.lines() {
            let line = line?;
            if line.starts_with("KEY:") {
                let key_str = &line[4..];
                if let Some(ch) = key_str.chars().next() {
                    let out = self.handle_key(ch);
                    if out.consumed {
                        writeln!(stdout, "ACTION:DELETE:{}", out.delete_count)?;
                        writeln!(stdout, "ACTION:INSERT:{}", out.insert_text)?;
                    } else {
                        writeln!(stdout, "ACTION:PASSTHROUGH")?;
                    }
                    stdout.flush()?;
                }
            } else if line == "MODE:UNICODE" {
                self.set_mode(BijoyMode::Unicode);
                writeln!(stdout, "OK:MODE:UNICODE")?;
                stdout.flush()?;
            } else if line == "MODE:CLASSIC" {
                self.set_mode(BijoyMode::Classic);
                writeln!(stdout, "OK:MODE:CLASSIC")?;
                stdout.flush()?;
            } else if line == "MODE:ENGLISH" {
                self.set_mode(BijoyMode::English);
                writeln!(stdout, "OK:MODE:ENGLISH")?;
                stdout.flush()?;
            } else if line == "RESET" {
                self.engine.reset();
                writeln!(stdout, "OK:RESET")?;
                stdout.flush()?;
            }
        }

        Ok(())
    }
}

